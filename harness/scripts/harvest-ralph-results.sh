#!/usr/bin/env bash
# harvest-ralph-results.sh — write RALPH_50ITER_RESULT.md from runtime artifacts.
#
# Designed to run after a ralph supervisor exit. Idempotent — safe to invoke
# multiple times; rewrites the result file each time. No external deps beyond
# jq, awk, sort. Reads only from output/ralph/, harness/ralph/STATE.json,
# and the ralph supervisor log path passed in.
#
# Usage:
#   bash harvest-ralph-results.sh [SUPERVISOR_LOG]
#
# SUPERVISOR_LOG defaults to /tmp/ralph-50iter.log.
#
# Output: RALPH_50ITER_RESULT.md
#
# This is meant to be the user's first read after a long autonomous ralph run.
# Tells them what ralph did, what it touched, what cost, and what next.

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
RALPH_DIR="$REPO_ROOT/harness/ralph"
LOG_DIR="$REPO_ROOT/output/ralph"
STATE_FILE="$RALPH_DIR/STATE.json"
JOURNAL_FILE="$RALPH_DIR/JOURNAL.md"
TODO_FILE="$RALPH_DIR/TODO.md"
LEARNINGS_FILE="$RALPH_DIR/LEARNINGS.md"
SUPERVISOR_LOG="${1:-/tmp/ralph-50iter.log}"

OUT="$REPO_ROOT/RALPH_50ITER_RESULT.md"

ts() { date -u +"%Y-%m-%dT%H:%M:%SZ"; }

# Pull stats from STATE.json
if [ -f "$STATE_FILE" ]; then
  iter=$(jq -r '.iteration // 0' "$STATE_FILE")
  cum_cost=$(jq -r '.cumulative_cost_usd // 0' "$STATE_FILE")
  cost_budget=$(jq -r '.cost_budget_usd // 0' "$STATE_FILE")
  max_iter=$(jq -r '.max_iterations // 0' "$STATE_FILE")
  stop_reason=$(jq -r '.stop_reason // "running"' "$STATE_FILE")
  started_at=$(jq -r '.started_at // ""' "$STATE_FILE")
  stopped_at=$(jq -r '.stopped_at // ""' "$STATE_FILE")
  last_phase=$(jq -r '.current_phase // "?"' "$STATE_FILE")
  last_action=$(jq -r '.last_action // "?"' "$STATE_FILE")
else
  iter=0; cum_cost=0; cost_budget=0; max_iter=0
  stop_reason="state_file_missing"; started_at="?"; stopped_at="?"
  last_phase="?"; last_action="?"
fi

# TODO progress
todo_open=0
todo_done=0
if [ -f "$TODO_FILE" ]; then
  todo_open=$(grep -c '^- \[ \]' "$TODO_FILE" 2>/dev/null || echo 0)
  todo_done=$(grep -c '^- \[x\]' "$TODO_FILE" 2>/dev/null || echo 0)
fi

# Iter log inventory
iter_logs=$(ls -1 "$LOG_DIR"/iter-*.json 2>/dev/null | wc -l | tr -d ' ')
iter_logs_text=$(ls -1 "$LOG_DIR"/iter-*.log 2>/dev/null | wc -l | tr -d ' ')

# Per-iter cost histogram (top 5 most expensive iters)
top_costly=""
if [ -d "$LOG_DIR" ]; then
  top_costly=$(
    for f in "$LOG_DIR"/iter-*.json; do
      [ -f "$f" ] || continue
      base=$(basename "$f" .json)
      cost=$(jq -r '.total_cost_usd // 0' "$f" 2>/dev/null)
      printf '%s\t%s\n' "$cost" "$base"
    done | sort -rn | head -5
  )
fi

# Recent LEARNINGS entries (those added during this run, by timestamp filter)
new_learnings=""
if [ -f "$LEARNINGS_FILE" ] && [ -n "$started_at" ]; then
  new_learnings=$(awk -v ts="$started_at" '
    /^\[20[0-9]+/ { keep = ($0 >= "[" ts) }
    keep { print }
  ' "$LEARNINGS_FILE" | head -120)
fi

# git changes since start (commits + working-tree diff stat)
new_commits=""
if [ -n "$started_at" ]; then
  cd "$REPO_ROOT"
  new_commits=$(git log --since="$started_at" --oneline 2>/dev/null | head -20)
fi

# Iter restored events (state-file integrity warnings)
if [ -f "$SUPERVISOR_LOG" ]; then
  restored=$(grep -c "RESTORED state files" "$SUPERVISOR_LOG" 2>/dev/null | head -1)
else
  restored=0
fi
[ -z "$restored" ] && restored=0

# Build the result file
{
cat <<EOF
# Ralph 50-iter Result — $(ts)

> Auto-generated by \`harness/scripts/harvest-ralph-results.sh\` after the
> supervisor exited. Read this first to understand what ralph did and didn't.

---

## Top-line

| Metric | Value |
|---|---|
| Iterations completed | **${iter} / ${max_iter}** |
| Stop reason | \`${stop_reason}\` |
| Cumulative cost | \$${cum_cost} (budget \$${cost_budget}) |
| TODO done / open | ${todo_done} done, ${todo_open} open |
| Last phase | \`${last_phase}\` (action: \`${last_action}\`) |
| Started | ${started_at} |
| Stopped | ${stopped_at} |
| State-file restores triggered | ${restored} |
| Iter JSON artifacts | ${iter_logs} |
| Iter human-readable logs | ${iter_logs_text} |

---

## Cost (top 5 most expensive iters)

\`\`\`
$top_costly
\`\`\`

---

## Commits during this run

\`\`\`
$new_commits
\`\`\`

(empty = no auto-commits, only TODO/JOURNAL/LEARNINGS state changes)

---

## LEARNINGS appended during this run

\`\`\`
$new_learnings
\`\`\`

---

## Supervisor log (last 25 lines)

\`\`\`
$(tail -25 "$SUPERVISOR_LOG" 2>/dev/null || echo "(supervisor log not found at $SUPERVISOR_LOG)")
\`\`\`

---

## Reading order for next session

1. **This file** — top-line + cost + commits.
2. \`SESSION_RESULT_2026-05-09.md\` — broader session context.
3. \`harness/ralph/JOURNAL.md\` — per-iter narrative (tail -50).
4. \`harness/ralph/LEARNINGS.md\` — full lessons accumulator.
5. \`output/ralph/iter-NNNN.json\` — drill-down per iteration if needed.

---

## What to do next

EOF

# Tailored next-step suggestions
case "$stop_reason" in
  all_todos_done|stop_signal_in_journal|converged)
    echo "Ralph **converged** — every queued task ran to completion. P0/P1/P2/P3 phases"
    echo "should all be at their targets. Re-run \`make validate-all\` to confirm."
    ;;
  cost_budget_exhausted)
    echo "Ralph **hit the \$${cost_budget} budget**. To continue, raise budget and"
    echo "\`make ralph\` --resume."
    ;;
  max_iter_reached)
    echo "Ralph **hit the ${max_iter}-iter cap**. If \`todo_open=${todo_open}\` items remain,"
    echo "either raise \`--max-iter\` and resume, or triage what's left manually."
    ;;
  state_file_missing|state_file_restored)
    echo "Ralph saw a **state file integrity event** (count=${restored}). The wrapper"
    echo "auto-recovered; review the supervisor log + iter logs for the offending"
    echo "iteration. Reinforce AGENT-INVARIANT in RALPH_PROMPT.md if this is a"
    echo "new agent pattern."
    ;;
  stalled_5_iter)
    echo "Ralph **stalled** — 5 consecutive iters with no TODO progress. Review"
    echo "the last few iter logs to understand what blocked the agent. Often this"
    echo "means a TIER-2 work-order required human-required tier (RLS) or hit"
    echo "guard.json. Triage what's blocking and unstick manually."
    ;;
  *)
    echo "Ralph stopped with reason \`${stop_reason}\`. See supervisor log above"
    echo "and the most recent iter log for diagnostic detail."
    ;;
esac

cat <<'EOF'

---

## Resume cheatsheet

```bash
# Continue from where ralph left off (preserves TODO/JOURNAL/STATE):
bash harness/ralph/supervisor.sh \
  --max-iter 100 --cost-budget 30 \
  --max-restarts 2 --cooldown 60

# Or fresh start (wipes state):
rm -f harness/ralph/{STATE.json,TODO.md,JOURNAL.md}
bash harness/ralph/supervisor.sh ...

# Validate without ralph:
make -C products/sediment validate-all
```
EOF
} > "$OUT"

echo "wrote: $OUT"
echo "iter=${iter}/${max_iter} cost=\$${cum_cost} stop=${stop_reason}"
exit 0
